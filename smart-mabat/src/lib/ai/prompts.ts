export function buildUserPrompt(ctx: GenerationContext): string {
  const s = ctx.settings;
  const lines = [
    `נושא מרכזי לפוסט הזה: ${ctx.categoryLabel}.`,
    `רעיונות לזווית (אפשר לבחור אחד או זווית אחרת באותו נושא): ${ctx.angleSuggestions.join(" | ")}`,
    "",
    "נושאים שכבר פורסמו לאחרונה – אסור לחזור עליהם או על אותו פתיח:",
    ctx.recentTopics.length ? ctx.recentTopics.map((t) => `- ${t}`).join("\n") : "- (אין עדיין)",
    "",
    `הנעה לפעולה מועדפת: ${s.cta_text}`,
    s.phone ? `טלפון לפרסום: ${s.phone}` : "אין טלפון לפרסום – אל תמציא מספר.",
    s.website ? `אתר: ${s.website}` : "אין אתר – אל תמציא כתובת.",
    s.service_area ? `אזור שירות: ${s.service_area}` : "אל תציין אזור שירות ספציפי.",
    `האשטגים קבועים של המותג (יתווספו אוטומטית, אל תחזור עליהם): ${s.brand_hashtags.join(" ")}`,
  ];
  if (s.extra_instructions?.trim()) lines.push("", `הנחיות נוספות מהמנהל: ${s.extra_instructions.trim()}`);
  if (ctx.avoidNote) lines.push("", `הניסיון הקודם נפסל בבדיקות: ${ctx.avoidNote}. כתוב פוסט שונה שעומד בכללים.`);
  return lines.join("\n");
}
