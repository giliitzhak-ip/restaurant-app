import type { Settings } from "../types";

export interface GenerationContext {
  categoryKey: string;
  categoryLabel: string;
  angleSuggestions: string[];
  recentTopics: string[]; // most recent first
  settings: Pick<
    Settings,
    "cta_text" | "brand_hashtags" | "phone" | "website" | "service_area" | "extra_instructions"
  >;
  avoidNote?: string; // feedback from a failed previous attempt
}

